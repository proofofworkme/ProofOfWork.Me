#!/usr/bin/env python3
"""Real synthetic lineage and exact-byte prior-policy migration; no live operations."""
import importlib.util, pathlib, subprocess, types, unittest
from unittest.mock import patch
HERE=pathlib.Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('hold_integration_fixtures',HERE/'check-lifecycle-remote.test.py')
T=importlib.util.module_from_spec(spec);spec.loader.exec_module(T)
F,R,I=T.F,T.R,T.I
class PreservationIntegration(unittest.TestCase):
 setUp=T.RemoteTests.setUp
 tearDown=T.RemoteTests.tearDown
 initialize=T.RemoteTests.initialize
 https=T.RemoteTests.https
 prepare=T.RemoteTests.prepare
 vps_prepared=T.RemoteTests.vps_prepared
 vps_complete=T.RemoteTests.vps_complete
 publish_vps_fixture=T.RemoteTests.publish_vps_fixture
 verify_candidate_package=T.RemoteTests.verify_candidate_package
 def test_old_policy_upgrade_and_next_zero_delete_cycle_preserve_both_holds(self):
  self.vps_complete()
  older='aaaaaaaa0003-20261101T010000Z'
  held='aaaaaaaa0004-20261103T010000Z'
  introducer='aaaaaaaa0005-20261104T010000Z'
  following='aaaaaaaa0006-20261105T010000Z'
  self.publish_vps_fixture(older);self.publish_vps_fixture(held)
  state,_=self.runtime.state();index,_=R.read_json(state['index']['path'],state['index']['sha256'])
  fallback_pins=dict(archive=index['admissions'][-2]['sha256'],root=index['admissions'][-1]['sha256'])
  with patch.object(F.S,'PRESERVED_FALLBACK_PREDECESSOR',older),patch.object(F.S,'PRESERVED_FALLBACK_INTRODUCER',held),patch.object(F.P,'FALLBACK_ADMISSION_SHA256',fallback_pins):
   forecast=self.runtime.dispatch('status',{'requireComplete':True,'prospectiveRelease':introducer})['privateStageRetention']
   self.publish_vps_fixture(introducer,forecast)
   state,state_sha=self.runtime.state();index,_=R.read_json(state['index']['path'],state['index']['sha256'])
   pins=dict(archive=index['admissions'][-2]['sha256'],root=index['admissions'][-1]['sha256'])
   # Load the actual previous committed verifier, not a mock that removes a field.
   old=types.ModuleType('prior_e99_policy');old.__file__=str(HERE.parent/'audit30/ui-release-policy.py');old._BOUND_STORAGE=F.S
   source=subprocess.check_output(['git','-C',str(HERE.parents[1]),'show','e99e149:deploy/audit30/ui-release-policy.py'])
   exec(compile(source,old.__file__,'exec'),old.__dict__)
   old.FALLBACK_ADMISSION_SHA256=fallback_pins
   # Synthetic history was generated by the candidate storage fixture. Admit
   # that exact writer digest, retaining all real plan/physical verification.
   old.KNOWN_RETIREMENT_CONTROLLERS.add(R.sha(pathlib.Path(F.S.__file__).read_bytes()))
   with patch.object(F.S,'PRESERVED_1042_PREDECESSOR',held),patch.object(F.S,'PRESERVED_1042_INTRODUCER',introducer),patch.object(F.P,'PRESERVED_1042_ADMISSIONS',pins):
    old_scope=old.policy_scope(state['index'],self.layout,R.APPROVAL_SHA)
    self.assertNotIn('preservedRelease1042',old_scope)
    self.assertEqual(old_scope['eligible'],[])
    before=self.runtime.state_path.read_bytes()
    with patch.object(self.runtime,'P',old):
     review=I.completed_review(self.runtime,{'mode':'completed-cycle','stateSha256':state_sha})
     result=self.verify_candidate_package(review)
     # A mismatching predecessor cannot be migrated even though old completion
     # was valid. Admission hashes remain the same so derivation refuses.
     with patch.object(F.S,'PRESERVED_1042_PREDECESSOR',older):
      with self.assertRaises(ValueError):self.verify_candidate_package(review)
    self.assertTrue(result['fullCompletionVerified'])
    self.assertEqual(self.runtime.state_path.read_bytes(),before)
    extra=result['preservedRelease1042'];paths=F.S.preserved_1042_paths(self.layout)
    self.assertEqual(set(extra['snapshotSha256']),set(paths))
    both=paths+F.S.preserved_fallback_paths(self.layout)
    snapshots={p:F.S.snapshot(pathlib.Path(p))['sha256'] for p in both}
    status=self.runtime.dispatch('status',{'requireComplete':True,'prospectiveRelease':following})
    self.assertEqual(status['verifiedPreservedRelease1042'],extra)
    forecast=status['privateStageRetention'];self.assertEqual(forecast['wouldRetire'],[])
    self.assertEqual(forecast['preservedFallback'],old_scope['preservedFallback'])
    prep=self.publish_vps_fixture(following,forecast)
    plan,_=R.read_json(prep['ordinaryPlan']['path'],prep['ordinaryPlan']['sha256'])
    self.assertEqual((plan['delete'],plan['moves'],plan['policyScope']['eligible']),([],[],[]))
    self.assertEqual(plan['policyScope']['preservedRelease1042'],extra)
    self.assertEqual({p:F.S.snapshot(pathlib.Path(p))['sha256'] for p in both},snapshots)
    state,_=self.runtime.state()
    closure=F.P.custody_closure(state['index']['path'],state['index']['sha256'],self.layout,R.APPROVAL_SHA)
    self.assertTrue(set(both)<=set(closure['protectedPaths']))
    self.assertTrue(self.runtime.dispatch('status',{'requireComplete':True})['retentionComplete'])
    # Exact held-byte replacement must refuse, even with identical file content.
    target=pathlib.Path(paths[2]);replacement=target.with_name('replacement-fixture')
    replacement.write_bytes(target.read_bytes());replacement.replace(target)
    with self.assertRaises(ValueError):self.runtime.dispatch('status',{'requireComplete':True})
if __name__=='__main__':unittest.main()
